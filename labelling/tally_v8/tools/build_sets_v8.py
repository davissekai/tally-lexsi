"""Step 5: build the v8 SFT train and val sets from the labels.

    python tools/build_sets_v8.py
Do not edit this file.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import v8lib as L  # noqa: E402
from validate_v8 import load_state, check_batch  # noqa: E402


def main():
    state = load_state()
    labels, bad = [], []
    for b in state["index"]:
        e, objs = check_batch(state, b)
        if e:
            if (ROOT / "labels" / f"{b['batch']}.jsonl").is_file():
                bad.append(b["batch"])
            continue
        labels += objs
    if bad:
        print("These batch files still have errors; fix them first:", bad[:20])
        sys.exit(1)
    train, val, stats = L.build_sets(state["chunks"], labels)
    L.write_sets(ROOT / "out", train, val, stats)
    print(json.dumps({k: stats[k] for k in ["labelled_chunks", "n_train", "n_val", "train_kinds", "val_kinds", "val_groups"]}, indent=1))
    print("Wrote out/train_sft_messages.jsonl, out/val_sft_messages.jsonl, *_with_metadata.jsonl, stats.json")


if __name__ == "__main__":
    main()
