"""Step 7: zip the results for Renhuang/Indi.

    python tools/make_return_zip.py
Creates tally_v8_return.zip next to TASK.md. Do not edit this file.
"""
import json
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import v8lib as L  # noqa: E402


def main():
    rep_p = ROOT / "work" / "validation_report.json"
    rep = json.loads(L.read_text(rep_p)) if rep_p.is_file() else None
    if not rep or rep.get("n_errors") != 0:
        print("Run  python tools/validate_v8.py --final  until it says VALID: 0 errors, then run this again.")
        sys.exit(1)
    out = ROOT / "tally_v8_return.zip"
    files = sorted((ROOT / "labels").glob("batch_*.jsonl")) + sorted((ROOT / "out").glob("*")) + [
        ROOT / "work" / "manifest.json", ROOT / "work" / "validation_report.json", ROOT / "work" / "batches_index.json"]
    notes = ROOT / "AGENT_NOTES.md"
    if notes.is_file():
        files.append(notes)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for p in files:
            if p.is_file():
                z.write(p, p.relative_to(ROOT).as_posix())
    print(f"Wrote {out.name} with {len(files)} files. Hand this file back to Renhuang.")


if __name__ == "__main__":
    main()
