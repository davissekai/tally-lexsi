"""Print the next batch to label (the first batch without a complete, valid labels file).

    python tools/next_batch.py
Do not edit this file.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import v8lib as L  # noqa: E402
from validate_v8 import load_state, check_batch  # noqa: E402


def main():
    state = load_state()
    done = 0
    for b in state["index"]:
        errs, _ = check_batch(state, b)
        if errs:
            name = b["batch"]
            print(f"NEXT {name}")
            print(f"  read:  work/batches/{name}.md")
            print(f"  write: labels/{name}.jsonl  ({len(b['chunk_ids'])} lines)")
            print(f"  check: python tools/validate_v8.py --batch {name[-4:]}")
            print(f"progress: {done}/{len(state['index'])} batches valid")
            return
        done += 1
    print(f"ALL DONE: {done}/{len(state['index'])} batches valid. Go to step 5 in TASK.md.")


if __name__ == "__main__":
    main()
