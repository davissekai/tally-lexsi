# Chunk sizes, in *estimated* Tiny Aya tokens (len(chars) / CHARS_PER_TOKEN).
# CHARS_PER_TOKEN is deliberately low (conservative) so real token counts are
# at or below the estimate; checked against the real tokenizer at ingest.
CHARS_PER_TOKEN = 3.5
TARGET_TOKENS = 1500     # soft cap: start a new chunk before exceeding this
HARD_TOKENS = 2000       # never exceed (a whole table may push a chunk up to here)
MIN_TOKENS = 450         # do not cut at a heading before a chunk has this much
OVERLAP_TOKENS = 200     # carried over when a section is split mid-way
LINE_SPLIT_TOKENS = 1400 # a single over-long block is cut into pieces of this size

QUOTE_MAX_WORDS = 50
BATCH_SIZE = 8           # chunks per labelling batch file
MIN_BATCHES_FINAL = 140  # a usable v8 set needs at least batches 0001-0140

# ---------------------------------------------------------------- text utils
_PUA = re.compile("[\ue000-\uf8ff]")


def est_tokens(s: str) -> int:
    return int(math.ceil(len(s) / CHARS_PER_TOKEN))


def flat(s: str) -> str:
    """Canonical form for quote checks: every whitespace run -> one space."""
    return re.sub(r"\s+", " ", s or "").strip()


def sha256_text(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def sha256_file(p) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def read_text(p) -> str:
    return Path(p).read_bytes().decode("utf-8")


def write_text(p, s: str):
    Path(p).parent.mkdir(parents=True, exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(s)


def load_jsonl(p):
    rows = []
    with open(p, encoding="utf-8", newline="") as f:
        data = f.read()
    for i, line in enumerate(data.split("\n"), 1):
        if line.strip():
            rows.append((i, line))
    return rows


def write_jsonl(p, rows):
    Path(p).parent.mkdir(parents=True, exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")


def project_of_doc(doc: str) -> str:
    return re.split(r"[_\-]", doc, maxsplit=1)[0]


# ---------------------------------------------------------------- chunker
PAGE_RE = re.compile(r"^--- page (\d+) ---\s*$", re.M)
HEADING_RE = re.compile(r"^(\d{1,2}(?:\.\d{1,2}){0,3})\.?\s+([A-Z(\u00c0-\u024f][^\n]{1,110})$")
NUM_ONLY_RE = re.compile(r"^(\d{1,2}(?:\.\d{1,2}){1,3})\.?$")


def _clean_raw(text: str) -> str:
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = text.replace("\u2028", "\n").replace("\u2029", "\n").replace("\x0c", "\n")
    text = text.replace("\u00a0", " ").replace("\t", "    ")
    text = _PUA.sub("\u2022", text)
    return text


def _is_tablish(raw_line: str) -> bool:
    s = raw_line.strip()
    if not s:
        return False
    gaps = len(re.findall(r"\S\s{3,}\S", s))
    nums = len(re.findall(r"\d[\d,.'\u2019 ]*\d|\d", s))
    if gaps >= 2:
        return True
    if gaps >= 1 and nums >= 2:
        return True
    return False


def _heading(line: str):
    """Return (number, title) if a cleaned line is a numbered section heading."""
    if len(line) > 120 or re.search(r"\.{4,}|\u2026{2,}", line):
        return None
    m = HEADING_RE.match(line)
    if not m:
        return None
    num, title = m.group(1), m.group(2).strip()
    if int(num.split(".")[0]) > 12:
        return None
    if re.search(r"%|\d{1,2}/\d{1,2}/\d{2,4}|\b(19|20)\d\d\b", title):
        return None
    words = title.split()
    if len(words) > 16 or len(words) == 0:
        return None
    if sum(ch.isdigit() for ch in title) > max(4, len(title) // 4):
        return None
    if title.endswith((",", ";")) or re.search(r"\s\d+$", title):
        return None  # list item or TOC line ending with a page number
    parts = [int(x) for x in num.split(".")]
    if parts[0] == 0:
        return None
    if re.search(r"https?:|www\.|<|>|@|\|", title) or title.endswith((":", ".", "-")):
        return None
    if len(parts) == 1:
        # top-level: short and heading-cased, so footnotes like '15 See ...' are skipped
        caps = sum(1 for w in words if w[:1].isupper() or not w[:1].isalpha())
        if len(words) > 9 or re.search(r"\d", title) or caps < 0.6 * len(words) or re.match(r"(See|In|The|This|For|As|It)\b", title):
            return None
    return num, title


def parse_pages(text: str):
    """[(page_no, raw_page_text)] using '--- page N ---' markers."""
    text = _clean_raw(text)
    marks = list(PAGE_RE.finditer(text))
    if not marks:
        return [(1, text)]
    out = []
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
        out.append((int(m.group(1)), text[m.end():end]))
    return out


def _strip_running_lines(pages):
    """Drop repeated running headers/footers (top/bottom 4 non-empty lines of a page)."""
    zone = 4
    counts = collections.Counter()
    page_lines = []
    for pno, raw in pages:
        lines = raw.split("\n")
        clean = [re.sub(r"\s+", " ", l).strip() for l in lines]
        nonempty = [i for i, c in enumerate(clean) if c]
        zidx = set(nonempty[:zone] + nonempty[-zone:])
        keys = set()
        for i in zidx:
            if len(clean[i]) <= 120:
                keys.add(re.sub(r"\d+", "#", clean[i]))
        for k in keys:
            counts[k] += 1
        page_lines.append((pno, lines, clean, zidx))
    n = len(pages)
    thresh = max(3, int(0.3 * n))
    drop_keys = {k for k, c in counts.items() if c >= thresh and n >= 5}
    out = []
    for pno, lines, clean, zidx in page_lines:
        keep = []
        for i, (raw, c) in enumerate(zip(lines, clean)):
            if i in zidx and c:
                k = re.sub(r"\d+", "#", c)
                if k in drop_keys or re.fullmatch(r"(page )?#( of #)?", k, re.I):
                    continue
            keep.append((raw, c))
        out.append((pno, keep))
    return out


def _blocks(pages_kept):
    """Yield blocks: dict(page, lines[clean], raw[list], kind in {'text','table','heading'})."""
    blocks = []
    for pno, lines in pages_kept:
        cur = []

        def flush():
            if cur:
                blocks.append({"page": pno, "raw": [r for r, _ in cur], "lines": [c for _, c in cur]})
            cur.clear()

        i = 0
        while i < len(lines):
            raw, c = lines[i]
            if not c:
                flush()
                i += 1
                continue
            h = None if _is_tablish(raw) else _heading(c)
            if h is None and NUM_ONLY_RE.match(c):
                # number on its own line, title on the next non-empty line
                j = i + 1
                while j < len(lines) and not lines[j][1]:
                    j += 1
                if j < len(lines):
                    cand = c + " " + lines[j][1]
                    h2 = _heading(cand)
                    if h2 is not None and len(lines[j][1].split()) <= 10:
                        flush()
                        blocks.append({"page": pno, "raw": [raw, lines[j][0]], "lines": [c, lines[j][1]],
                                       "heading": h2})
                        i = j + 1
                        continue
            if h is not None:
                flush()
                blocks.append({"page": pno, "raw": [raw], "lines": [c], "heading": h})
                i += 1
                continue
            cur.append((raw, c))
            i += 1
        flush()
    for b in blocks:
        if "heading" in b:
            b["kind"] = "heading"
        else:
            tab = sum(1 for r in b["raw"] if _is_tablish(r))
            b["kind"] = "table" if len(b["raw"]) >= 2 and tab * 2 >= len(b["raw"]) else "text"
        b["text"] = "\n".join(b["lines"])
        b["tok"] = est_tokens(b["text"]) + 1
    # merge adjacent table blocks on the same page (tables often have blank rows)
    merged = []
    for b in blocks:
        if merged and b["kind"] == "table" and merged[-1]["kind"] == "table" and merged[-1]["page"] == b["page"]:
            m = merged[-1]
            m["lines"] = m["lines"] + [""] + b["lines"]
            m["raw"] = m["raw"] + [""] + b["raw"]
            m["text"] = "\n".join(m["lines"])
            m["tok"] = est_tokens(m["text"]) + 1
        else:
            merged.append(b)
    return merged


def _split_big(b):
    """Cut a block that alone exceeds HARD_TOKENS into line groups."""
    pieces, cur, cur_tok = [], [], 0
    for line in b["lines"]:
        # extremely long single line: hard-wrap at a space
        segs = [line]
        if est_tokens(line) > LINE_SPLIT_TOKENS:
            segs, s = [], line
            lim = int(LINE_SPLIT_TOKENS * CHARS_PER_TOKEN)
            while len(s) > lim:
                cut = s.rfind(" ", 0, lim)
                cut = cut if cut > lim // 2 else lim
                segs.append(s[:cut].rstrip())
                s = s[cut:].lstrip()
            segs.append(s)
        for seg in segs:
            t = est_tokens(seg) + 1
            if cur and cur_tok + t > LINE_SPLIT_TOKENS:
                pieces.append(cur)
                cur, cur_tok = [], 0
            cur.append(seg)
            cur_tok += t
    if cur:
        pieces.append(cur)
    out = []
    for i, p in enumerate(pieces):
        nb = dict(b)
        nb["lines"] = p
        nb["text"] = "\n".join(p)
        nb["tok"] = est_tokens(nb["text"]) + 1
        nb["part"] = i
        out.append(nb)
    return out


def _render(blocks):
    """Body text with '--- page N ---' markers whenever the page changes."""
    parts, last = [], None
    for b in blocks:
        if b["page"] != last:
            parts.append(f"--- page {b['page']} ---")
            last = b["page"]
        parts.append(b["text"])
    return "\n\n".join(parts)


def chunk_document(doc: str, text: str):
    """Section-aware chunks for one document. Returns list of chunk dicts."""
    pages = parse_pages(text)
    kept = _strip_running_lines(pages)
    blocks = []
    for b in _blocks(kept):
        blocks.extend(_split_big(b) if b["tok"] > HARD_TOKENS else [b])

    # attach section path to every block
    stack = {}
    for b in blocks:
        if b["kind"] == "heading":
            num, title = b["heading"]
            depth = num.count(".") + 1
            for d in list(stack):
                if d >= depth:
                    del stack[d]
            stack[depth] = f"{num} {title}"
        b["section"] = " > ".join(stack[d] for d in sorted(stack)[-2:]) if stack else ""

    chunks, cur, cur_tok = [], [], 0
    carried = 0  # how many leading blocks of `cur` were carried as overlap

    def emit():
        nonlocal cur, cur_tok, carried
        if cur and len(cur) > carried:
            chunks.append(list(cur))
        cur, cur_tok, carried = [], 0, 0

    for b in blocks:
        t = b["tok"]
        is_head = b["kind"] == "heading"
        depth = b["heading"][0].count(".") + 1 if is_head else 99
        if cur and is_head and ((depth <= 2 and cur_tok >= MIN_TOKENS) or cur_tok >= 0.6 * TARGET_TOKENS):
            emit()
        elif cur and cur_tok + t > TARGET_TOKENS and not (b["kind"] == "table" and cur_tok + t <= HARD_TOKENS and cur_tok < MIN_TOKENS):
            # size cut inside a section: carry trailing blocks as overlap
            prev = cur
            emit()
            tail, tt = [], 0
            for pb in reversed(prev):
                if pb["kind"] == "heading" or tt + pb["tok"] > OVERLAP_TOKENS:
                    break
                tail.insert(0, pb)
                tt += pb["tok"]
            if tail and tt + t <= HARD_TOKENS:
                cur, cur_tok, carried = list(tail), tt, len(tail)
        cur.append(b)
        cur_tok += t
    emit()

    out = []
    for i, cb in enumerate(chunks):
        body = _render(cb)
        section = cb[0].get("section") or "(document start)"
        crumb = f"[Section: {section}]"
        pages_in = [b["page"] for b in cb]
        out.append({
            "chunk_id": f"{doc}::v8-{i:04d}",
            "doc": doc,
            "project": project_of_doc(doc),
            "chunk_index": i,
            "start_page": min(pages_in),
            "end_page": max(pages_in),
            "section": section,
            "text": crumb + "\n" + body,
            "est_tokens": est_tokens(crumb + "\n" + body),
            "has_table": any(b["kind"] == "table" for b in cb),
        })
    return out


def chunk_body(chunk_text: str) -> str:
    """Chunk text without the leading [Section: ...] line (quotes must come from here)."""
    if chunk_text.startswith("[Section: "):
        nl = chunk_text.find("\n")
        return chunk_text[nl + 1:] if nl != -1 else ""
    return chunk_text


