SEED = 42


def load_sources(pkg_root):
    pkg_root = Path(pkg_root)
    meta = json.loads(read_text(pkg_root / "sources" / "SOURCES.json"))
    return meta["documents"]


def build_corpus(pkg_root):
    """Chunk every source document. Returns (chunks, errors)."""
    pkg_root = Path(pkg_root)
    errs, chunks = [], []
    for d in load_sources(pkg_root):
        p = pkg_root / d["file"]
        if not p.is_file():
            errs.append(f"missing source file {d['file']}")
            continue
        if sha256_file(p) != d["sha256"]:
            errs.append(f"source file changed (sha256 mismatch): {d['file']}")
            continue
        if d["project"] in BANNED_PROJECTS or BANNED_NAME_RE.search(d["doc"]):
            errs.append(f"banned project in sources: {d['doc']}")
            continue
        for c in chunk_document(d["doc"], read_text(p)):
            c["project_group"] = d["project_group"]
            c["doc_type"] = d["doc_type"]
            c["score"] = priority_score(c["text"])
            chunks.append(c)
    return chunks, errs


def _round_robin(items, key):
    groups = collections.OrderedDict()
    for it in items:
        groups.setdefault(key(it), []).append(it)
    out = []
    lists = list(groups.values())
    i = 0
    while any(lists):
        for l in lists:
            if l:
                out.append(l.pop(0))
        lists = [l for l in lists if l]
        i += 1
    return out


def select_queue(chunks, priority_ids=()):
    """Deterministic label queue: known-value chunks first, then high-signal chunks, plus likely-empty ones.

    priority_ids: chunk ids that contain a value found by an earlier labelling round (v7). Only the
    ids are used, never the old values.
    """
    prio = set(priority_ids)
    pos_pool = sorted([c for c in chunks if c["chunk_id"] in prio],
                      key=lambda c: (-c["score"], c["chunk_id"]))
    pos_pool += sorted([c for c in chunks if c["score"] >= POS_MIN_SCORE and c["chunk_id"] not in prio],
                       key=lambda c: (-c["score"], c["chunk_id"]))
    per_g, per_d, pos = collections.Counter(), collections.Counter(), []
    for c in pos_pool:
        if c["chunk_id"] in prio:
            per_g[c["project_group"]] += 1
            per_d[c["doc"]] += 1
            pos.append(c)
            continue
        if len(pos) >= N_POS:
            break
        if per_g[c["project_group"]] >= MAX_PER_GROUP or per_d[c["doc"]] >= MAX_PER_DOC:
            continue
        per_g[c["project_group"]] += 1
        per_d[c["doc"]] += 1
        pos.append(c)
    pos = _round_robin(pos, key=lambda c: c["project_group"])
    rng = random.Random(SEED)
    neg_pool = sorted([c for c in chunks if c["score"] == 0 and c["est_tokens"] >= 300 and c["chunk_id"] not in prio],
                      key=lambda c: c["chunk_id"])
    rng.shuffle(neg_pool)
    neg_pool = _round_robin(neg_pool, key=lambda c: c["project_group"])
    neg = neg_pool[:N_NEG]
    queue = []
    pi = ni = 0
    while pi < len(pos) or ni < len(neg):
        for _ in range(BATCH_SIZE - 1):
            if pi < len(pos):
                queue.append(pos[pi]); pi += 1
        if ni < len(neg):
            queue.append(neg[ni]); ni += 1
    return queue


def batches_of(queue):
    return [queue[i:i + BATCH_SIZE] for i in range(0, len(queue), BATCH_SIZE)]


def batch_name(i: int) -> str:
    return f"batch_{i + 1:04d}"


def render_batch(name, chunks):
    out = [f"# {name}: {len(chunks)} chunks",
           "",
           f"Write your labels to `labels/{name}.jsonl`: exactly {len(chunks)} lines, one JSON object per chunk, in this order:",
           ""]
    for i, c in enumerate(chunks, 1):
        out.append(f"{i}. `{c['chunk_id']}`")
    out.append("")
    out.append("Rules: RULES_V8.md. Quotes must be copied character for character from the text between <<<TEXT and TEXT>>> (not from the hints, not from the [Section: ...] line).")
    for c in chunks:
        out.append("")
        out.append(f"======== CHUNK {c['chunk_id']} ========")
        out.append(f"doc: {c['doc']} | doc_type: {c['doc_type']} | pages {c['start_page']}-{c['end_page']}")
        hints = hint_lines(c["text"])
        if hints:
            out.append("Auto-found lines that mention a field keyword next to a number. HINTS ONLY: they can be wrong, irrelevant or incomplete. Read the whole text.")
            for fs, line in hints:
                out.append(f"- [{', '.join(fs)}] {line}")
        else:
            out.append("Auto-found lines: none (this chunk is probably all not_stated, but read it).")
        out.append("<<<TEXT")
        out.append(c["text"])
        out.append("TEXT>>>")
    return "\n".join(out) + "\n"


def chunk_record(c):
    keys = ["chunk_id", "doc", "project", "project_group", "doc_type", "chunk_index",
            "start_page", "end_page", "section", "est_tokens", "has_table", "score", "text"]
    return {k: c[k] for k in keys}


# ---------------------------------------------------------------- SFT set builder
VAL_FRAC = 0.15
NEG_SHARE = 0.25          # empty full examples, at most this share of full examples
SF_NOT_STATED_RATIO = 0.30
WEAK_OVERSAMPLE = 2       # train copies of weak-field single-field + conflict examples
MAX_TRAIN_EXAMPLES = 9000
VAL_MIN_PER_FIELD = 6


def _answer7(lab, chunk):
    out = {}
    for f in FIELDS:
        v = lab["fields"][f]
        if not isinstance(v, dict):
            out[f] = "not stated"
            continue
        out[f] = {"value": format_value(v["value"], v["unit"]),
                  "page": page_of(chunk["text"], v["quote"], chunk["start_page"]),
                  "quote": v["quote"]}
    return out


def _ex(eid, chunk, kind, field, user, answer, positive):
    return {
        "id": eid, "doc": chunk["doc"], "project": chunk["project"],
        "project_group": chunk["project_group"], "chunk_index": chunk["chunk_index"],
        "start_page": chunk["start_page"], "end_page": chunk["end_page"],
        "positive_fields": positive, "est_tokens": est_tokens(user), "source": "v8_gemini_label",
        "example_kind": kind, "field": field,
        "messages": [{"role": "user", "content": user},
                     {"role": "assistant", "content": json.dumps(answer, ensure_ascii=False)}],
    }


def _pick_val_groups(examples, rng):
    groups = sorted({e["project_group"] for e in examples})
    total = len(examples)
    by_g = collections.defaultdict(list)
    for e in examples:
        by_g[e["project_group"]].append(e)
    best, best_score = None, None
    for _ in range(3000):
        order = groups[:]
        rng.shuffle(order)
        chosen, n = [], 0
        for g in order:
            c = len(by_g[g])
            if n + c > 0.20 * total:
                continue
            chosen.append(g)
            n += c
            if n >= 0.13 * total:
                break
        sf = collections.Counter(e["field"] for g in chosen for e in by_g[g] if e["example_kind"] == "single_field_stated")
        short = sum(max(0, VAL_MIN_PER_FIELD - sf[f]) for f in FIELDS)
        score = abs(n / total - VAL_FRAC) + 0.02 * short
        if best is None or score < best_score:
            best, best_score = sorted(chosen), score
    return set(best or [])


def build_sets(chunks_by_id, labels):
    """labels: list of validated label objects. Returns (train, val, stats)."""
    rng = random.Random(SEED)
    full_pos, full_neg, sf_pos, sf_hard_neg, sf_neg_pool, picks = [], [], [], [], [], []
    for lab in sorted(labels, key=lambda l: l["chunk_id"]):
        c = chunks_by_id[lab["chunk_id"]]
        if c["project"] in BANNED_PROJECTS:
            continue
        ans = _answer7(lab, c)
        pos = [f for f in FIELDS if isinstance(ans[f], dict)]
        ex = _ex(c["chunk_id"], c, "full", None, user_message(PROMPT, c["start_page"], c["end_page"], c["text"]), ans, pos)
        (full_pos if pos else full_neg).append(ex)
        conf_by_f = collections.defaultdict(list)
        for k in lab["conflicts"]:
            conf_by_f[k["field"]].append(k)
        for f in FIELDS:
            user = user_message(single_field_header(f), c["start_page"], c["end_page"], c["text"])
            item = _ex(f"{c['chunk_id']}::sf-{f}", c,
                       "single_field_stated" if f in pos else "single_field_not_stated", f, user, {f: ans[f]},
                       [f] if f in pos else [])
            if f in pos:
                sf_pos.append(item)
            elif conf_by_f.get(f):
                item["example_kind"] = "single_field_hard_negative"
                sf_hard_neg.append(item)
            elif pos:
                sf_neg_pool.append(item)
            # conflict-resolution example
            if conf_by_f.get(f):
                cands = []
                if f in pos:
                    v = lab["fields"][f]
                    cands.append({"value": format_value(v["value"], v["unit"]), "quote": v["quote"], "chosen": True})
                for k in conf_by_f[f]:
                    cands.append({"value": format_value(k["value"], k["unit"]), "quote": k["quote"], "chosen": False, "code": k["code"]})
                crng = random.Random(f"{c['chunk_id']}|{f}")
                crng.shuffle(cands)
                letters = {id(x): chr(65 + i) for i, x in enumerate(cands)}
                rejected = "; ".join(f"{letters[id(x)]}) {REJECT_CODES[x['code']]}" for x in cands if not x["chosen"])
                if f in pos:
                    chosen = [x for x in cands if x["chosen"]][0]
                    rule = PICK_FOR_CODE[conf_by_f[f][0]["code"]]
                    reason = f"{letters[id(chosen)]} is correct. {PICK_RULES[rule]} Rejected: {rejected}"
                else:
                    reason = f"None of the candidates fits the field definition. Rejected: {rejected}"
                user = user_message(conflict_header(f, cands), c["start_page"], c["end_page"], c["text"])
                answer = {"reason": reason, f: ans[f]}
                picks.append(_ex(f"{c['chunk_id']}::pick-{f}", c, "conflict_pick", f, user, answer, [f] if f in pos else []))

    # empty full examples capped at NEG_SHARE of full set
    n_neg_cap = int(round(NEG_SHARE * len(full_pos) / (1 - NEG_SHARE)))
    rng.shuffle(full_neg)
    full_neg_kept = full_neg[:n_neg_cap]
    # plain not_stated single-field: fill up to the ratio after hard negatives, spread across fields
    n_sf_neg = max(0, int(round(SF_NOT_STATED_RATIO * len(sf_pos))) - len(sf_hard_neg))
    by_f = collections.defaultdict(list)
    for it in sf_neg_pool:
        by_f[it["field"]].append(it)
    for f in by_f:
        rng.shuffle(by_f[f])
    sf_neg = []
    while len(sf_neg) < n_sf_neg and any(by_f.values()):
        for f in FIELDS:
            if by_f[f] and len(sf_neg) < n_sf_neg:
                sf_neg.append(by_f[f].pop())
    examples = full_pos + full_neg_kept + sf_pos + sf_hard_neg + sf_neg + picks

    val_groups = _pick_val_groups(examples, random.Random(SEED + 1))
    train = [e for e in examples if e["project_group"] not in val_groups]
    val = [e for e in examples if e["project_group"] in val_groups]

    # oversample weak fields in TRAIN only
    extra = []
    for e in train:
        if e["field"] in WEAK_FIELDS and e["example_kind"] in ("single_field_stated", "conflict_pick", "single_field_hard_negative"):
            for k in range(WEAK_OVERSAMPLE - 1):
                d = dict(e)
                d["id"] = f"{e['id']}::dup{k + 1}"
                d["example_kind"] = e["example_kind"]
                d["oversampled"] = True
                extra.append(d)
    train = train + extra
    capped = 0
    if len(train) > MAX_TRAIN_EXAMPLES:
        # drop strong-field plain single-field stated examples first
        drop_pool = [e for e in train if e["example_kind"] == "single_field_stated" and e["field"] not in WEAK_FIELDS]
        rng.shuffle(drop_pool)
        drop = {id(e) for e in drop_pool[:len(train) - MAX_TRAIN_EXAMPLES]}
        capped = len(drop)
        train = [e for e in train if id(e) not in drop]
    rng.shuffle(train)
    val.sort(key=lambda e: e["id"])
    for e in train:
        e["split"] = "train"
    for e in val:
        e["split"] = "val"

    def kinds(rows):
        return dict(sorted(collections.Counter(r["example_kind"] for r in rows).items()))

    def fieldpos(rows, kind):
        return dict(sorted(collections.Counter(r["field"] for r in rows if r["example_kind"] == kind).items()))

    stats = {
        "version": V8_VERSION,
        "labelled_chunks": len(labels),
        "full_positive": len(full_pos), "full_empty_pool": len(full_neg), "full_empty_kept": len(full_neg_kept),
        "single_field_stated": len(sf_pos), "single_field_hard_negative": len(sf_hard_neg),
        "single_field_not_stated": len(sf_neg), "conflict_pick": len(picks),
        "n_train": len(train), "n_val": len(val),
        "train_kinds": kinds(train), "val_kinds": kinds(val),
        "train_field_stated_sf": fieldpos(train, "single_field_stated"),
        "val_field_stated_sf": fieldpos(val, "single_field_stated"),
        "train_conflict_pick_by_field": fieldpos(train, "conflict_pick"),
        "val_groups": sorted(val_groups),
        "train_groups": sorted({e["project_group"] for e in train}),
        "group_overlap": sorted(val_groups & {e["project_group"] for e in train}),
        "capped_dropped": capped,
        "max_est_tokens": max((e["est_tokens"] for e in train + val), default=0),
        "settings": {"VAL_FRAC": VAL_FRAC, "NEG_SHARE": NEG_SHARE, "SF_NOT_STATED_RATIO": SF_NOT_STATED_RATIO,
                     "WEAK_OVERSAMPLE": WEAK_OVERSAMPLE, "WEAK_FIELDS": WEAK_FIELDS, "MAX_TRAIN_EXAMPLES": MAX_TRAIN_EXAMPLES},
    }
    return train, val, stats


def write_sets(out_dir, train, val, stats):
    out_dir = Path(out_dir)
    msgs = lambda rows: [{"messages": r["messages"]} for r in rows]
    write_jsonl(out_dir / "train_sft_messages.jsonl", msgs(train))
    write_jsonl(out_dir / "val_sft_messages.jsonl", msgs(val))
    write_jsonl(out_dir / "train_with_metadata.jsonl", train)
    write_jsonl(out_dir / "val_sft_with_metadata.jsonl", val)
    write_text(out_dir / "stats.json", json.dumps(stats, indent=2, ensure_ascii=False) + "\n")
