def _norm_value(v: str) -> str:
    return re.sub(r"[\s,'\u2019]", "", str(v)).lower()


def validate_label_line(obj, chunk_text: str, chunk_id: str):
    """Return list of error strings for one label object (empty list = valid)."""
    errs = []
    E = lambda m: errs.append(f"{chunk_id}: {m}")
    if not isinstance(obj, dict):
        return [f"{chunk_id}: line is not a JSON object"]
    if set(obj) != {"chunk_id", "fields", "conflicts"}:
        E(f"top-level keys must be exactly chunk_id, fields, conflicts (got {sorted(obj)})")
    if obj.get("chunk_id") != chunk_id:
        E(f"chunk_id is {obj.get('chunk_id')!r}, expected {chunk_id!r}")
    body_flat = flat(chunk_body(chunk_text))
    fields = obj.get("fields")
    conflicts = obj.get("conflicts")
    if not isinstance(fields, dict):
        E("fields must be an object")
        fields = {}
    if not isinstance(conflicts, list):
        E("conflicts must be a list ([] when none)")
        conflicts = []
    if isinstance(fields, dict) and set(fields) != set(ALL_FIELDS):
        E(f"fields must have exactly these 9 keys: {ALL_FIELDS} (got {sorted(fields)})")

    def check_quote(where, value, quote):
        if not isinstance(quote, str) or not quote.strip():
            E(f"{where}: quote is empty")
            return
        if quote != quote.strip() or "  " in quote or "\n" in quote or "\t" in quote:
            E(f"{where}: quote must be a single line with single spaces and no leading/trailing space")
        if quote.startswith("[Section:") or quote.startswith("--- page"):
            E(f"{where}: quote must not include the [Section: ...] line or a page marker")
        if "--- page" in quote:
            E(f"{where}: quote must not span a '--- page N ---' marker")
        nw = len(quote.split())
        if nw > QUOTE_MAX_WORDS:
            E(f"{where}: quote has {nw} words (max {QUOTE_MAX_WORDS})")
        if flat(quote) not in body_flat:
            E(f"{where}: quote is not an exact substring of the chunk text (copy it again character for character)")
        if not isinstance(value, str) or not value.strip():
            E(f"{where}: value is empty")
        elif value not in quote:
            E(f"{where}: value {value!r} is not an exact substring of its quote")

    def check_unit(where, f, value, unit):
        if unit not in UNITS[f]:
            E(f"{where}: unit {unit!r} not allowed for {f}; allowed: {sorted(map(str, UNITS[f]))}")
        if not isinstance(value, str):
            return
        if f != "additionality" and f != "crediting_period" and not re.search(r"\d", value):
            E(f"{where}: value for {f} must contain a number")
        if f == "additionality" and len(value.split()) > 40:
            E(f"{where}: additionality value must be at most 40 words")
        if f == "crediting_period":
            years = re.findall(r"(?<!\d)(19\d\d|20\d\d|21\d\d)(?!\d)", value)
            if len(years) < 2:
                E(f"{where}: crediting_period value must contain a start year and an end year (two 4-digit years); otherwise use not_stated")
        if f == "permanence_buffer":
            m = re.search(r"\d+(?:[.,]\d+)?", value)
            if m and not (0 < float(m.group(0).replace(",", ".")) <= 100):
                E(f"{where}: permanence_buffer must be a percentage between 0 and 100")
        if f in ("estimated_reductions", "estimated_reductions_pre_buffer", "leakage", "baseline", "area", "area_incl_leakage_belt"):
            if len(value.split()) > 4:
                E(f"{where}: value must be just the number as written (no words); put the unit in unit")

    stated = {}
    for f in ALL_FIELDS:
        v = fields.get(f, "not_stated") if isinstance(fields, dict) else "not_stated"
        if v == "not_stated":
            continue
        if not isinstance(v, dict):
            E(f"{f}: must be the string \"not_stated\" or an object")
            continue
        if set(v) != {"value", "quote", "unit"}:
            E(f"{f}: object keys must be exactly value, quote, unit; got {sorted(v)}")
            continue
        check_quote(f, v["value"], v["quote"])
        check_unit(f, f, v["value"], v["unit"])
        stated[f] = v

    conf_fields = collections.Counter()
    for k, c in enumerate(conflicts):
        where = f"conflicts[{k}]"
        if not isinstance(c, dict) or set(c) != {"field", "value", "quote", "unit", "code"}:
            E(f"{where}: must be an object with exactly field, value, quote, unit, code")
            continue
        f = c["field"]
        if f not in ALL_FIELDS:
            E(f"{where}: unknown field {f!r}")
            continue
        conf_fields[f] += 1
        if c["code"] not in FIELD_REJECT_CODES[f]:
            E(f"{where}: code {c['code']!r} not allowed for {f}; allowed: {sorted(FIELD_REJECT_CODES[f])}")
        check_quote(where, c["value"], c["quote"])
        if c["unit"] is not None and not isinstance(c["unit"], str):
            E(f"{where}: unit must be a string or null")
        if f in stated and _norm_value(c["value"]) == _norm_value(stated[f]["value"]):
            E(f"{where}: conflict value equals the chosen value for {f}; remove it (same number repeated is not a conflict)")

    for f, n in conf_fields.items():
        if n > MAX_CONFLICTS_PER_FIELD:
            E(f"{f}: {n} conflicts listed; at most {MAX_CONFLICTS_PER_FIELD} per field (never list every row of a per-year or per-stratum table)")
    # cross-field rules
    for k, c in enumerate(conflicts):
        if isinstance(c, dict) and c.get("code") == "R_PRE_BUFFER" and "estimated_reductions_pre_buffer" not in stated:
            E(f"conflicts[{k}]: R_PRE_BUFFER used, so fill estimated_reductions_pre_buffer with that figure")
        if isinstance(c, dict) and c.get("code") == "R_AREA_INCL_BELT" and "area_incl_leakage_belt" not in stated:
            E(f"conflicts[{k}]: R_AREA_INCL_BELT used, so fill area_incl_leakage_belt with that figure")
    return errs


