def has_number(line: str) -> bool:
    """True if the line has a real figure (ignores CO2, section numbers, versions, table/equation refs)."""
    return bool(NUM_RE.search(_NOISE_NUM.sub(" ", line)))


def field_signals(text: str):
    """Fields whose keyword appears on a line that also has a digit (or additionality keyword)."""
    hits = collections.Counter()
    for line in chunk_body(text).split("\n"):
        low = line.lower()
        for f, pat in FIELD_KEYS.items():
            if re.search(pat, low):
                if f == "additionality" or has_number(line):
                    hits[f] += 1
    return hits


def hint_lines(text: str, limit=10):
    """Verbatim lines that mention a field keyword next to a number."""
    out, seen = [], set()
    for line in chunk_body(text).split("\n"):
        if len(line) > 260 or len(line) < 12 or line in seen:
            continue
        low = line.lower()
        fs = [f for f, pat in FIELD_KEYS.items() if re.search(pat, low)
              and (f == "additionality" or has_number(line))]
        if fs:
            seen.add(line)
            out.append((fs, line))
        if len(out) >= limit:
            break
    return out


FIELD_WEIGHTS = {"crediting_period": 3.0, "leakage": 3.0, "permanence_buffer": 2.0, "additionality": 2.0,
                 "area": 1.5, "estimated_reductions": 1.0, "baseline": 1.0}


def priority_score(text: str) -> float:
    h = field_signals(text)
    return round(sum(FIELD_WEIGHTS[f] * min(c, 3) for f, c in h.items()), 2)


