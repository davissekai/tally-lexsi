def format_value(value, unit) -> str:
    v = str(value).strip()
    if unit is None:
        return v
    u = str(unit).strip()
    if not u or u.lower() in SKIP_UNITS:
        return v
    if u == "%":
        return v if v.rstrip().endswith("%") else v + "%"
    if u.lower() in v.lower():
        return v
    if u.lower() == "ha" and re.search(r"\bhectares?\b", v, re.I):
        return v
    return f"{v} {u}"


def page_of(chunk_text: str, quote: str, fallback):
    """Page of the first text segment (between page markers) containing the quote."""
    body = chunk_body(chunk_text)
    target = flat(quote)
    page = fallback
    for s in re.split(r"(--- page \d+ ---)", body):
        m = re.fullmatch(r"--- page (\d+) ---", s)
        if m:
            page = int(m.group(1))
        elif target and target in flat(s):
            return page
    return fallback


