"""Validator. Run until it prints "VALID: 0 errors".

    python tools/validate_v8.py                 # everything (labels so far + built sets)
    python tools/validate_v8.py --batch 0007    # one batch only (fast)
    python tools/validate_v8.py --final         # final check: all batches done + built sets
Do not edit this file.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import v8lib as L  # noqa: E402

MAX_SHOWN = 60


def load_state():
    work = ROOT / "work"
    if not (work / "manifest.json").is_file():
        print("work/manifest.json missing: run  python tools/chunk_v8.py  first")
        sys.exit(1)
    chunks = {}
    for _, line in L.load_jsonl(work / "chunks_all.jsonl"):
        o = json.loads(line)
        chunks[o["chunk_id"]] = o
    index = json.loads(L.read_text(work / "batches_index.json"))
    return {"chunks": chunks, "index": index, "manifest": json.loads(L.read_text(work / "manifest.json"))}


def check_batch(state, b):
    """(errors, label_objects) for one batch; a missing file is one error."""
    name = b["batch"]
    p = ROOT / "labels" / f"{name}.jsonl"
    if not p.is_file():
        return [f"{name}: labels/{name}.jsonl does not exist yet"], []
    errs, objs = [], []
    lines = L.load_jsonl(p)
    ids = b["chunk_ids"]
    if len(lines) != len(ids):
        errs.append(f"{name}: has {len(lines)} non-empty lines, expected exactly {len(ids)} (one per chunk)")
    for k, (lineno, line) in enumerate(lines):
        expected = ids[k] if k < len(ids) else None
        try:
            obj = json.loads(line)
        except json.JSONDecodeError as exc:
            errs.append(f"{name} line {lineno}: invalid JSON ({exc.msg} at column {exc.colno}); escape any \" inside quotes as \\\"")
            continue
        if expected is None:
            errs.append(f"{name} line {lineno}: extra line (chunk {obj.get('chunk_id')!r} is not in this batch)")
            continue
        cid = obj.get("chunk_id") if isinstance(obj, dict) else None
        if cid != expected:
            errs.append(f"{name} line {lineno}: chunk_id {cid!r} but line {k + 1} must be {expected!r} (keep the batch order)")
            continue
        e = L.validate_label_line(obj, state["chunks"][expected]["text"], expected)
        errs.extend(f"{name} line {lineno}: {x}" for x in e)
        if not e:
            objs.append(obj)
    return errs, objs


def leak_checks():
    errs = []
    meta = L.load_sources(ROOT)
    listed = {Path(d["file"]).name for d in meta}
    for d in meta:
        if d["project"] in L.BANNED_PROJECTS or L.BANNED_NAME_RE.search(d["doc"]):
            errs.append(f"LEAK: banned project in SOURCES.json: {d['doc']}")
    for p in (ROOT / "sources").iterdir():
        if p.name != "SOURCES.json" and p.name not in listed:
            errs.append(f"LEAK/EXTRA: unexpected file in sources/: {p.name} (delete it; only listed files are allowed)")
    id_re = re.compile(r'"(?:chunk_id|doc|id|project)"\s*:\s*"([^"]+)"')
    for folder in ("labels", "out", "work"):
        d = ROOT / folder
        if not d.is_dir():
            continue
        for p in sorted(d.rglob("*")):
            if not p.is_file() or p.suffix not in (".jsonl", ".json", ".md", ".csv", ".txt"):
                continue
            txt = L.read_text(p)
            for m in id_re.finditer(txt):
                v = m.group(1)
                if L.project_of_doc(v) in L.BANNED_PROJECTS or L.BANNED_NAME_RE.search(v.split("::")[0]):
                    errs.append(f"LEAK: banned project id {v!r} in {p.relative_to(ROOT)}")
                    break
    return errs


def check_sets(state, labels_ok):
    errs = []
    out = ROOT / "out"
    need = ["train_sft_messages.jsonl", "val_sft_messages.jsonl", "train_with_metadata.jsonl",
            "val_sft_with_metadata.jsonl", "stats.json"]
    missing = [n for n in need if not (out / n).is_file()]
    if missing:
        return [f"out/: missing {missing}: run  python tools/build_sets_v8.py"]
    train = [json.loads(l) for _, l in L.load_jsonl(out / "train_with_metadata.jsonl")]
    val = [json.loads(l) for _, l in L.load_jsonl(out / "val_sft_with_metadata.jsonl")]
    tg = {r["project_group"] for r in train}
    vg = {r["project_group"] for r in val}
    if tg & vg:
        errs.append(f"SPLIT: project_group in both train and val: {sorted(tg & vg)}")
    if not val:
        errs.append("SPLIT: val set is empty")
    for r in train + val:
        if r["project"] in L.BANNED_PROJECTS:
            errs.append(f"LEAK: banned project {r['project']} in built sets ({r['id']})")
        msgs = r.get("messages") or []
        if len(msgs) != 2 or msgs[0]["role"] != "user" or msgs[1]["role"] != "assistant":
            errs.append(f"SETS: {r['id']}: messages must be [user, assistant]")
            continue
        ans = json.loads(msgs[1]["content"])
        body = L.flat(L.chunk_body(msgs[0]["content"].split("\n\nPages ", 1)[-1].split(":\n\n", 1)[-1]))
        for f, v in ans.items():
            if f == "reason":
                continue
            if isinstance(v, dict) and L.flat(v["quote"]) not in body:
                errs.append(f"SETS: {r['id']}: {f} quote not in its own prompt text")
    # rebuild must match exactly
    t2, v2, _ = L.build_sets(state["chunks"], labels_ok)
    if [e["id"] for e in t2] != [e["id"] for e in train] or [e["id"] for e in v2] != [e["id"] for e in val]:
        errs.append("SETS: out/ does not match the current labels: re-run  python tools/build_sets_v8.py")
    return errs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch", help="4-digit batch number, e.g. 0007")
    ap.add_argument("--final", action="store_true")
    a = ap.parse_args()
    state = load_state()
    errs = []
    if a.batch:
        name = f"batch_{int(a.batch):04d}"
        b = [x for x in state["index"] if x["batch"] == name]
        if not b:
            print(f"no such batch {name}")
            sys.exit(1)
        e, objs = check_batch(state, b[0])
        errs += e
        n_val = sum(1 for o in objs for f in L.ALL_FIELDS if isinstance(o["fields"].get(f), dict))
        summary = f"{name}: {len(objs)}/{len(b[0]['chunk_ids'])} chunks valid, {n_val} stated values"
    else:
        labels_ok, done, partial = [], 0, 0
        present = [(ROOT / "labels" / f"{b['batch']}.jsonl").is_file() for b in state["index"]]
        last = max([i for i, p in enumerate(present) if p], default=-1)
        if a.final:
            if last + 1 < L.MIN_BATCHES_FINAL:
                errs.append(f"FINAL: only {last + 1} batches labelled; at least {L.MIN_BATCHES_FINAL} (batch_0001 to batch_{L.MIN_BATCHES_FINAL:04d}) are required, all {len(state['index'])} preferred")
            gaps = [state["index"][i]["batch"] for i in range(last + 1) if not present[i]]
            if gaps:
                errs.append(f"FINAL: batches must be done in order with no gaps; missing {gaps[:10]}")
        for b in state["index"]:
            e, objs = check_batch(state, b)
            if e and not (ROOT / "labels" / f"{b['batch']}.jsonl").is_file():
                continue
            if e:
                partial += 1
                errs += e
            else:
                done += 1
                labels_ok += objs
        extra = sorted(p.name for p in (ROOT / "labels").glob("*") if p.stem not in {b["batch"] for b in state["index"]})
        errs += [f"labels/: unexpected file {x} (only batch_NNNN.jsonl files are allowed)" for x in extra]
        errs += leak_checks()
        if a.final or (ROOT / "out" / "stats.json").is_file():
            errs += check_sets(state, labels_ok)
        summary = f"{done}/{len(state['index'])} batches valid, {partial} batch files with errors, {len(labels_ok)} chunks labelled"
        report = {"summary": summary, "n_errors": len(errs), "errors": errs[:2000], "final": a.final}
        L.write_text(ROOT / "work" / "validation_report.json", json.dumps(report, indent=1, ensure_ascii=False) + "\n")
    for e in errs[:MAX_SHOWN]:
        print("ERROR", e)
    if len(errs) > MAX_SHOWN:
        print(f"... and {len(errs) - MAX_SHOWN} more errors (see work/validation_report.json)")
    print(summary)
    if errs:
        print(f"INVALID: {len(errs)} errors")
        sys.exit(1)
    print("VALID: 0 errors")


if __name__ == "__main__":
    main()
