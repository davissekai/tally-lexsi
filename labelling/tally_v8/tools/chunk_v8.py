"""Step 1: chunk the source documents and write the labelling batches.

Run from the package root (the folder that contains TASK.md):
    python tools/chunk_v8.py
Do not edit this file.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import v8lib as L  # noqa: E402


def build(work):
    chunks, errs = L.build_corpus(ROOT)
    if errs:
        print("CHUNKER FAILED:")
        for e in errs:
            print("  -", e)
        sys.exit(1)
    prio_p = ROOT / "expected" / "priority_chunk_ids.json"
    prio = json.loads(L.read_text(prio_p)) if prio_p.is_file() else []
    queue = L.select_queue(chunks, prio)
    (work / "batches").mkdir(parents=True, exist_ok=True)
    L.write_jsonl(work / "chunks_all.jsonl", [L.chunk_record(c) for c in chunks])
    batches = L.batches_of(queue)
    index = []
    for i, b in enumerate(batches):
        name = L.batch_name(i)
        L.write_text(work / "batches" / f"{name}.md", L.render_batch(name, b))
        index.append({"batch": name, "chunk_ids": [c["chunk_id"] for c in b]})
    L.write_text(work / "batches_index.json", json.dumps(index, indent=1, ensure_ascii=False) + "\n")
    L.write_jsonl(work / "label_queue.jsonl", [L.chunk_record(c) for c in queue])
    manifest = {
        "version": L.V8_VERSION,
        "n_chunks_all": len(chunks),
        "n_queue": len(queue),
        "n_batches": len(batches),
        "sha256_chunks_all": L.sha256_file(work / "chunks_all.jsonl"),
        "sha256_label_queue": L.sha256_file(work / "label_queue.jsonl"),
        "sha256_batches_index": L.sha256_file(work / "batches_index.json"),
    }
    L.write_text(work / "manifest.json", json.dumps(manifest, indent=1) + "\n")
    return manifest


def main():
    import shutil
    (ROOT / "labels").mkdir(exist_ok=True)
    work = ROOT / "work"
    exp_p = ROOT / "expected" / "manifest_expected.json"
    if "--package-build" in sys.argv:   # used once by Indi to create the package
        m = build(work)
        L.write_text(exp_p, json.dumps(m, indent=1) + "\n")
        print("package build:", m)
        return
    exp = json.loads(L.read_text(exp_p))
    regen = ROOT / "work_regen_check"
    if regen.exists():
        shutil.rmtree(regen)
    m = build(regen)
    shutil.rmtree(regen)
    if all(m[k] == exp.get(k) for k in m):
        print("Manifest matches expected/manifest_expected.json")
    else:
        print("NOTE: this computer's chunker output differs slightly from the expected manifest")
        print("(usually a different Python version). The shipped work/ files are canonical and are used. Continue.")
    if not (work / "manifest.json").is_file() or json.loads(L.read_text(work / "manifest.json")) != exp:
        print("STOP: work/ is missing or was modified. Re-extract the package and tell Renhuang.")
        sys.exit(2)
    print(f"OK: {exp['n_chunks_all']} chunks in total, {exp['n_queue']} to label in {exp['n_batches']} batches of up to {L.BATCH_SIZE}.")
    print("Batch files: work/batches/batch_0001.md ...")


if __name__ == "__main__":
    main()
